// Runtime support (appended only when used)

static const char* RuntimeMultiply = R"(
; r0 = r0 * r1   (clobbers r1-r3)
.rt_mul:
    mov r2, r0
    li r0, 0
.rt_mul_loop:
    cmpi r1, 0
    beq .rt_mul_done
    li r3, 1
    and r3, r1, r3
    cmpi r3, 0
    beq .rt_mul_skip
    add r0, r0, r2
.rt_mul_skip:
    add r2, r2, r2
    li r3, 1
    shr r1, r1, r3
    bra .rt_mul_loop
.rt_mul_done:
    ret
)";

static const char* RuntimeDivide = R"(
; unsigned: r0 = r0 / r1, r1 = r0 % r1   (clobbers r2, r3)
.rt_divu:
    li r2, 0
    li r3, 16
.rt_divu_loop:
    add r2, r2, r2
    cmpi r0, 0
    bpl .rt_divu_nobit
    addi r2, r2, 1
.rt_divu_nobit:
    add r0, r0, r0
    cmp r2, r1
    bltu .rt_divu_next
    sub r2, r2, r1
    addi r0, r0, 1
.rt_divu_next:
    addi r3, r3, -1
    cmpi r3, 0
    bne .rt_divu_loop
    mov r1, r2
    ret

; signed: r0 = r0 / r1, r1 = r0 % r1 (truncating, C semantics)
.rt_divs:
    push lr
    push r0
    xor r2, r0, r1
    push r2
    cmpi r0, 0
    bge .rt_divs_a
    neg r0, r0
.rt_divs_a:
    cmpi r1, 0
    bge .rt_divs_b
    neg r1, r1
.rt_divs_b:
    call .rt_divu
    pop r2
    cmpi r2, 0
    bge .rt_divs_c
    neg r0, r0
.rt_divs_c:
    pop r2
    cmpi r2, 0
    bge .rt_divs_d
    neg r1, r1
.rt_divs_d:
    pop lr
    ret
)";

static const char* RuntimeMemcpy = R"(
; copy r2 bytes from [r0] to [r1]; returns r0 = destination
.rt_memcpy:
    push r1
.rt_memcpy_loop:
    cmpi r2, 0
    beq .rt_memcpy_done
    lb r3, [r0]
    sb r3, [r1]
    addi r0, r0, 1
    addi r1, r1, 1
    addi r2, r2, -1
    bra .rt_memcpy_loop
.rt_memcpy_done:
    pop r0
    ret
)";

static const char* RuntimeMemzero = R"(
; zero r1 bytes at [r0]
.rt_memzero:
    li r3, 0
.rt_memzero_loop:
    cmpi r1, 0
    beq .rt_memzero_done
    sb r3, [r0]
    addi r0, r0, 1
    addi r1, r1, -1
    bra .rt_memzero_loop
.rt_memzero_done:
    ret
)";

