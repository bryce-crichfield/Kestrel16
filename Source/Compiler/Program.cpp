// Data section

static string DataSection() {
    string out = "\n; ---- data\n";
    for (Var* global : globals) {
        if (global->type->kind == KindFunction || !global->isDefined) {
            continue;
        }
        int size = global->type->size;
        if (global->type->kind == KindArray && global->type->length < 0) {
            warnings.push_back(sourceName + ": warning: array '" + global->name + "' has no size; assuming one element");
            size = global->type->base->size;
        }
        if (size == 0) {
            size = 1;
        }
        if (global->type->align >= 2) {
            out += "    .align 2\n";
        }
        out += global->label + ":\n";
        if (!global->hasInit) {
            out += "    .space " + std::to_string(size) + "\n";
            continue;
        }
        global->data.resize(size, 0);
        string bytes;
        int count = 0;
        auto flush = [&]() {
            if (count) {
                out += "    .byte " + bytes + "\n";
            }
            bytes.clear();
            count = 0;
        };
        for (int offset = 0; offset < size;) {
            auto relocation = global->relocations.find(offset);
            if (relocation != global->relocations.end()) {
                const string& label = relocation->second.first;
                int addend = relocation->second.second;
                flush();
                out += "    .word " + label;
                if (addend > 0) {
                    out += "+" + std::to_string(addend);
                }
                else if (addend < 0) {
                    out += std::to_string(addend);  // the minus sign comes with the number
                }
                out += "\n";
                offset += 2;
                continue;
            }
            if (count) {
                bytes += ", ";
            }
            bytes += std::to_string(global->data[offset]);
            count++;
            if (count == 16) {
                flush();  // 16 bytes per .byte line
            }
            offset++;
        }
        flush();
    }
    return out;
}

string ProgramText() {
    char start[96];
    snprintf(start, sizeof start, "\n_start:\n    li sp, 0x%04X\n    la r4, _main\n    jalr r4\n    halt\n", Address::StackTop);
    string out;
    out += "; generated by KestrelCompiler from " + sourceName + "\n";
    out += start;
    out += code;
    if (useMultiply) {
        out += RuntimeMultiply;
    }
    if (useDivide) {
        out += RuntimeDivide;
    }
    if (useMemcpy) {
        out += RuntimeMemcpy;
    }
    if (useMemzero) {
        out += RuntimeMemzero;
    }
    out += DataSection();
    return out;
}

